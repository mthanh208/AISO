# -*- coding: utf-8 -*-
"""
sql_memory.py — Simple persistent memory using sqlite3 and pydantic for schema
"""
import sqlite3, json, os
try:
    from pydantic import BaseModel
except Exception:
    BaseModel = None

DB_NAME = os.path.join(os.path.dirname(__file__), '..', 'data', 'memory.db')

class DocumentSchema(BaseModel if BaseModel else object):
    id: int
    text: str
    source: str = ''
    weight: float = 1.0

class SQLMemory:
    def __init__(self, db_path=None):
        self.db_path = db_path or DB_NAME
        os.makedirs(os.path.dirname(self.db_path), exist_ok=True)
        self.conn = sqlite3.connect(self.db_path, check_same_thread=False)
        self._ensure()

    def _ensure(self):
        cur = self.conn.cursor()
        cur.execute('''CREATE TABLE IF NOT EXISTS documents (id INTEGER PRIMARY KEY, text TEXT, source TEXT, weight REAL)''')
        cur.execute('''CREATE TABLE IF NOT EXISTS feedback (id INTEGER PRIMARY KEY AUTOINCREMENT, doc_id INTEGER, sentiment INTEGER, ts INTEGER)''')
        self.conn.commit()

    def add_document(self, doc):
        cur = self.conn.cursor()
        cur.execute('INSERT OR REPLACE INTO documents (id, text, source, weight) VALUES (?,?,?,?)',
                    (doc.get('id'), doc.get('text'), doc.get('source'), doc.get('weight',1.0)))
        self.conn.commit()

    def get_top(self, limit=10):
        cur = self.conn.cursor()
        cur.execute('SELECT id, text, source, weight FROM documents ORDER BY weight DESC LIMIT ?', (limit,))
        return cur.fetchall()

    def add_feedback(self, doc_id, sentiment):
        cur = self.conn.cursor()
        cur.execute('INSERT INTO feedback (doc_id, sentiment, ts) VALUES (?,?,strftime("%s","now"))', (doc_id, sentiment))
        self.conn.commit()
PY
