# -*- coding: utf-8 -*-
"""
symbolic_engine.py — helpers for symbolic math/logic via sympy
"""
try:
    import sympy as sp
except Exception:
    sp = None

def simplify_expression(expr_str):
    if sp is None:
        return expr_str
    try:
        expr = sp.sympify(expr_str)
        return str(sp.simplify(expr))
    except Exception:
        return expr_str

# Simple boolean satisfiability check for small logical expressions
def is_satisfiable(expr_str):
    if sp is None:
        return None
    try:
        expr = sp.sympify(expr_str)
        return sp.simplify_logic(expr) is not None
    except Exception:
        return None
