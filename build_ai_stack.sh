# -*- coding: utf-8 -*-
"""
vector_index.py — Wrapper to use FAISS (if available) or TF-IDF + sklearn nearest
"""
try:
    import faiss
    HAS_FAISS = True
except Exception:
    HAS_FAISS = False

try:
    from sklearn.feature_extraction.text import TfidfVectorizer
    import numpy as np
except Exception:
    TfidfVectorizer = None
    np = None

class VectorIndex:
    def __init__(self, dim=128):
        self.dim = dim
        self.index = None
        self.texts = []
        self.vec = None

    def build_tfidf(self, texts):
        if TfidfVectorizer is None:
            raise RuntimeError('sklearn not installed')
        self.texts = texts
        self.vec = TfidfVectorizer(max_features=self.dim)
        X = self.vec.fit_transform(texts).astype('float32')
        if HAS_FAISS:
            import numpy as _np
            Xnp = _np.array(X.todense(), dtype='float32')
            self.index = faiss.IndexFlatIP(self.dim)
            self.index.add(Xnp)
        else:
            self.index = X

    def query(self, q, topk=5):
        if self.vec is None:
            return []
        qv = self.vec.transform([q]).astype('float32')
        if HAS_FAISS:
            import numpy as _np
            qnp = _np.array(qv.todense(), dtype='float32')
            D, I = self.index.search(qnp, topk)
            return [(self.texts[i], float(D[0][k])) for k, i in enumerate(I[0])]
        else:
            import numpy as _np
            from sklearn.metrics.pairwise import cosine_similarity
            sims = cosine_similarity(qv, self.index)[0]
            idx = sims.argsort()[::-1][:topk]
            return [(self.texts[i], float(sims[i])) for i in idx]
PY
