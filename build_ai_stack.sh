# -*- coding: utf-8 -*-
"""
ml_utils.py — helpers for classic ML using scikit-learn, numpy, pandas
- clustering, lightweight reranker (online SGD), tfidf vectorizer
"""
try:
    import numpy as np
    import pandas as pd
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.cluster import MiniBatchKMeans
    from sklearn.linear_model import SGDClassifier
except Exception:
    np = None
    pd = None

class SimpleReranker:
    def __init__(self):
        self.model = None
        self.vec = None

    def fit(self, texts, labels):
        if pd is None:
            return
        self.vec = TfidfVectorizer(max_features=2000)
        X = self.vec.fit_transform(texts)
        self.model = SGDClassifier(max_iter=1000)
        self.model.fit(X, labels)

    def predict_score(self, query, candidates):
        if self.model is None or self.vec is None:
            return [(c, 0.0) for c in candidates]
        qv = self.vec.transform([query])
        X = self.vec.transform(candidates)
        scores = self.model.decision_function(X)
        return list(zip(candidates, scores))

class TopicCluster:
    def __init__(self, k=8):
        self.k = k
        self.vec = None
        self.km = None

    def fit(self, texts):
        if pd is None:
            return
        self.vec = TfidfVectorizer(max_features=3000)
        X = self.vec.fit_transform(texts)
        self.km = MiniBatchKMeans(n_clusters=self.k)
        self.km.fit(X)

    def predict(self, texts):
        if self.km is None:
            return [0]*len(texts)
        X = self.vec.transform(texts)
        return self.km.predict(X)
