"""
ner_spacy.py — spaCy based entity extraction with lightweight fallback
"""
try:
    import spacy
    NLP = None
    # attempt to load small en model; for Vietnamese user may need a custom model
    try:
        NLP = spacy.load('en_core_web_sm')
    except Exception:
        try:
            NLP = spacy.blank('en')
        except Exception:
            NLP = None
except Exception:
    spacy = None
    NLP = None

import re
_TOKEN_RE = re.compile(r"[^\W\d_]+", re.UNICODE)

def extract_entities(text):
    if NLP:
        doc = NLP(text)
        ents = [ent.text for ent in doc.ents]
        if ents:
            return ents
    # fallback: capitalize-word heuristics
    words = _TOKEN_RE.findall(text)
    caps = [w for w in words if w.istitle()]
    return list(dict.fromkeys(caps))
