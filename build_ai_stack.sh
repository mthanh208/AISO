# -*- coding: utf-8 -*-
"""
sandbox.py — run subprocesses with resource/time limits (best-effort)
"""
import subprocess, threading, os, sys

def run_with_timeout(cmd, timeout=5):
    proc = subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    timer = threading.Timer(timeout, proc.kill)
    try:
        timer.start()
        out, err = proc.communicate()
        return proc.returncode, out.decode('utf-8', errors='ignore'), err.decode('utf-8', errors='ignore')
    finally:
        timer.cancel()
PY
