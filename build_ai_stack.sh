# -*- coding: utf-8 -*-
"""
workflow_orchestrator.py — simple orchestrator and hook for langgraph if installed
"""
try:
    import langgraph
    HAS_LANGGRAPH = True
except Exception:
    HAS_LANGGRAPH = False

class WorkflowOrchestrator:
    def __init__(self):
        self.has_langgraph = HAS_LANGGRAPH

    def run_pipeline(self, steps, context=None):
        context = context or {}
        for step in steps:
            func = step.get('func')
            args = step.get('args', [])
            kwargs = step.get('kwargs', {})
            if callable(func):
                try:
                    res = func(*args, **kwargs)
                    context[step.get('name','last')] = res
                except Exception as e:
                    context['error'] = str(e)
                    break
        return context
